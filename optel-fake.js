const isInternal = (link) => link.startsWith('/');

/** Fill defaults, rank pages, resolve scenarios. Throws on an unknown scenario. */
export function compileProfile(input = {}, { now = new Date() } = {}) {
  const p = { ...DEFAULT_PROFILE, ...input };
  const cwv = typeof p.cwv === 'string' ? CWV_PRESETS[p.cwv] : { ...CWV_PRESETS.average, ...p.cwv };
  if (!cwv) throw new Error(`profile.cwv must be good, average, poor or { lcp, cls, inp, ttfb }, not ${p.cwv}`);
  const pages = (p.pages && p.pages.length ? p.pages : genericPages()).map((pg, i) => ({
    path: pg.path || '/',
    share: pg.share ?? 1 / (i + 1) ** 0.85,
    blocks: (pg.blocks || []).map((b) => (typeof b === 'string' ? { name: b, links: [], media: 0 } : { links: [], media: 0, ...b }))
      .map((b) => ({ ...b, form: b.form ?? /form/i.test(b.name) })),
  }));
  const ranked = [...pages].sort((a, b) => b.share - a.share);
  const byPath = new Map(pages.map((pg) => [pg.path, pg]));
  // who links to whom: a navigation into a page comes from a page that links to it
  const linkedFrom = new Map();
  for (const pg of pages) {
    for (const b of pg.blocks) {
      for (const l of b.links) {
        if (isInternal(l) && byPath.has(l) && l !== pg.path) {
          if (!linkedFrom.has(l)) linkedFrom.set(l, []);
          linkedFrom.get(l).push(pg);
        }
      }
    }
  }
  const header = p.header || ranked.slice(0, 6).map((pg) => pg.path);
  const footer = p.footer || ranked.slice(6, 14).map((pg) => pg.path);

  const scenarios = (p.scenarios || []).map((s) => {
    const spec = typeof s === 'string' ? { name: s } : s;
    const def = SCENARIOS[spec.name];
    if (!def) throw new Error(`Unknown scenario "${spec.name}". Known: ${Object.keys(SCENARIOS).join(', ')}`);
    const merged = { ...def.defaults, ...spec };
    return { ...merged, from: resolveWhen(merged.from, now), to: resolveWhen(merged.to, now) };
  });
  const scenario = (name) => scenarios.find((s) => s.name === name);

  const deepScore = (pg) => pg.path.split('/').filter(Boolean).length;
  const ctx = {
    ...p,
    cwv,
    pages,
    ranked,
    byPath,
    linkedFrom,
    header,
    footer,
    scenarios,
    scenario,
    pageWeights: pages.map((pg) => [pg, pg.share]),
    // AI assistants cite deep pages more than search does; paid sends people to conversion pages
    landing: {
      ai: pages.map((pg) => [pg, pg.share ** 0.5 * (1 + deepScore(pg))]),
      paid: pages.map((pg) => [pg, pg.share * (/demo|trial|pricing|register|contact|signup/.test(pg.path) ? 6 : 1)]),
    },
  };
  ctx.perHour = (t) => {
    const local = (t.getUTCHours() + Math.round(p.timezoneOffset) + 48) % 24;
    const trend = (1 + p.growth) ** ((t.getTime() - EPOCH) / (30 * 864e5));
    return (p.viewsPerDay / p.weight / 24) * (DIURNAL[local] / DIURNAL_MEAN) * (WEEKDAY[t.getUTCDay()] / WEEKDAY_MEAN) * trend;
  };
  ctx.sourceMix = (t) => {
    const mix = { ...p.sources };
    const ai = scenario('ai-growth');
    const k = ai ? scenarioIntensity(ai, t) : 0;
    if (k > 0) {
      const base = mix.ai || 0;
      const target = base + (ai.share - base) * k;
      const others = Object.keys(mix).filter((key) => key !== 'ai');
      const rest = others.reduce((a, key) => a + mix[key], 0) || 1;
      others.forEach((key) => { mix[key] *= (1 - target) / rest; });
      mix.ai = target * (1 - ai.adsShare * k);
      mix['paid-ai'] = target * ai.adsShare * k;
    }
    return mix;
  };
  return ctx;
}

