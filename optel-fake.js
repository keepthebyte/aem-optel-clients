/** '2026-10-01', '-14d', '-6h', '+2d', 'now', a Date or epoch ms → Date (or null). */
export function resolveWhen(x, now = new Date()) {
  if (x == null || x === '') return null;
  if (x instanceof Date) return x;
  if (typeof x === 'number') return new Date(x);
  if (x === 'now') return new Date(now.getTime());
  const m = /^([+-]\d+)([hdw])$/.exec(String(x));
  if (m) return new Date(now.getTime() + Number(m[1]) * { h: 3600e3, d: 864e5, w: 7 * 864e5 }[m[2]]);
  const d = new Date(/^\d{4}-\d{2}-\d{2}$/.test(x) ? `${x}T00:00:00Z` : x);
  if (Number.isNaN(d.getTime())) throw new Error(`Not a date for a scenario: ${x}`);
  return d;
}

function scenarioIntensity(s, t) {
  const time = t.getTime();
  const from = s.from ? s.from.getTime() : -Infinity;
  const to = s.to ? s.to.getTime() : Infinity;
  if (time < from) return 0;
  if (s.mode === 'window') return time < to ? 1 : 0;
  if (s.mode === 'ramp' && Number.isFinite(from) && Number.isFinite(to) && to > from) return Math.min(1, (time - from) / (to - from));
  return 1;
}

