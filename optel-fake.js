const HELP = `optel-fake ${FAKE_VERSION}: synthetic Optel bundles for a site without data.

Build a profile from a site's pages (query-index.json or sitemap.xml, plus each page's blocks)
  node optel-fake.js profile --site https://main--site--org.aem.live [--max-pages 40] [--limit 300]
                             [--views-per-day 3000] [--cwv good|average|poor] [--scenario a,b] [--out profile.json]

List the scenarios and their options
  node optel-fake.js scenarios

Use it (no domain key, no network)
  node optel-client.js --fake [profile.json | https://site | (nothing: generic site)] [--scenario a,b] --report summary
  OPTEL_FAKE=profile.json OPTEL_FAKE_SCENARIO=ai-growth node optel-client.js --report ai --last 30d

Every bundle has fake: true and the CLI's meta says so. Never present fake numbers as measured.`;

function parseArgs(argv) {
  const out = { _: [] };
  for (let i = 0; i < argv.length; i += 1) {
    const a = argv[i];
    if (a.startsWith('--')) {
      const [k, inline] = a.slice(2).split(/=(.*)/s);
      if (inline !== undefined) out[k] = inline;
      else if (argv[i + 1] && !argv[i + 1].startsWith('--')) { out[k] = argv[i + 1]; i += 1; } else out[k] = true;
    } else out._.push(a);
  }
  return out;
}

async function cli(argv) {
  const args = parseArgs(argv);
  const cmd = args._[0];
  if (args.help || !cmd) { process.stdout.write(`${HELP}\n`); return; }
  if (cmd === 'scenarios') {
    const list = Object.entries(SCENARIOS).map(([name, s]) => ({ name, about: s.about, options: s.defaults }));
    process.stdout.write(`${JSON.stringify(list, null, 2)}\n`);
    return;
  }
  if (cmd !== 'profile') throw new Error(`Unknown command "${cmd}" (see --help)`);
  if (!args.site) throw new Error('profile needs --site https://…');
  const overrides = {};
  if (args['views-per-day']) overrides.viewsPerDay = Number(args['views-per-day']);
  if (args.cwv) overrides.cwv = args.cwv;
  if (args.scenario) overrides.scenarios = String(args.scenario).split(',').map((s) => s.trim()).filter(Boolean);
  const profile = await buildProfile({
    site: args.site,
    maxPages: Number(args['max-pages'] || 40),
    limit: Number(args.limit || 300),
    overrides,
    onProgress: (d, n) => process.stderr.write(`\rreading pages ${d}/${n}`),
  });
  compileProfile(profile);
  const blocks = new Set(profile.pages.flatMap((p) => p.blocks.map((b) => b.name)));
  process.stderr.write(`\r${profile.pages.length} pages, ${blocks.size} block types, header ${profile.header ? profile.header.length : 'default'} links\n`);
  const text = `${JSON.stringify(profile, null, 2)}\n`;
  if (args.out) { const { writeFile } = await import('node:fs/promises'); await writeFile(args.out, text); } else process.stdout.write(text);
}

function invokedDirectly() {
  if (typeof process === 'undefined' || !process.argv?.[1] || typeof import.meta === 'undefined') return false;
  try {
    const self = decodeURIComponent(new URL(import.meta.url).pathname);
    const arg = process.argv[1].replace(/\\/g, '/');
    return self === arg || self.endsWith(`/${arg.replace(/^\.?\//, '')}`) || self.replace(/^\/([A-Za-z]:)/, '$1') === arg;
  } catch { return false; }
}

if (invokedDirectly()) {
  cli(process.argv.slice(2)).catch((err) => {
    process.stderr.write(`\nerror: ${err.message || err}\n`);
    process.exitCode = 1;
  });
}
