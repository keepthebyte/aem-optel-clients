#!/usr/bin/env node
/*
 * optel-fake.js: synthetic Optel bundles for a site that has no data (yet).
 *
 * A new site, a demo, a POC before launch, a workshop without a domain key: the
 * reports, skills and panels need bundles. This file makes them, in the real shape,
 * so everything built on optel-client.js runs unchanged. It never touches the network
 * except to read a site's page list when you build a profile.
 *
 *   node optel-client.js --fake --report summary                        generic site, no key
 *   node optel-fake.js profile --site https://main--site--org.aem.live --out profile.json
 *   node optel-client.js --fake profile.json --scenario ai-growth --last 30d --report ai
 *   OPTEL_FAKE=profile.json node skills/…/scripts/pull.js …           any script that runs the CLI
 *
 *   import { loadBundles } from './optel-client.js';
 *   const { bundles } = await loadBundles({ fake: profile, last: '7d' });   // no key, no network
 *
 * THE RULE: fake numbers are never presented as measured. Every bundle carries
 * `fake: true`, loadBundles() returns `fake: true`, and the CLI puts FAKE_NOTE in `meta`.
 * Keep the label on every chart, report and slide built from them.
 *
 * HOW IT WORKS
 *   A PROFILE describes the site: its pages (with their blocks and links, read from the
 *   site's query-index.json or sitemap.xml and each page's .plain.html), views per day,
 *   the mix of devices and traffic sources, Core Web Vitals quality, bots, consent banner.
 *   Every field has a default, so `{}` is a valid profile (a generic B2B site).
 *
 *   Bundles are generated per UTC hour from a seed (profile.seed, the domain and the
 *   hour), so the same request always answers the same bundles, and hourly, daily and
 *   monthly loads of one range hold the same views: a daily file is its 24 hours, a
 *   monthly file is its hours subsampled 1 in `monthFactor` with the weight raised to
 *   match (like the real bundler, which subsamples coarse files).
 *
 *   SCENARIOS layer a story on top, between two dates: AI referrals that grow, an LCP
 *   regression, a dead-click hotspot, a broken link, a paid campaign, personal AI
 *   agents, an A/B experiment. Dates are absolute ('2026-10-01') or relative to now
 *   ('-14d', '-6h', 'now'). `node optel-fake.js scenarios` lists them with their options.
 */

