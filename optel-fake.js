const SKIP_PATHS = /^\/(library|drafts|fragments|tools|nav|footer|blocks|block-collection|sidekick)(\/|$)|\/(nav|footer|metadata)$/i;
const NOT_BLOCKS = new Set(['section-metadata', 'metadata', 'columns-wrapper']);
const decodeHtml = (s) => s.replace(/&#x26;|&amp;/g, '&').replace(/&#x3D;/g, '=').replace(/&#x27;|&#39;/g, "'").replace(/&quot;/g, '"');

function toLink(href, origin) {
  const raw = decodeHtml(href.trim());
  if (!raw || raw.startsWith('#') || /^(mailto|tel|javascript):/i.test(raw)) return null;
  let u;
  try { u = new URL(raw, `${origin}/`); } catch { return null; }
  if (!/^https?:$/.test(u.protocol)) return null;
  if (/\.(png|jpe?g|gif|webp|svg|mp4|pdf|riv|json)$/i.test(u.pathname) || /\/(blocks|icons|media)\//.test(u.pathname)) return null;
  if (u.origin === origin) {
    const p = u.pathname.replace(/\/index$/, '/').replace(/(.)\/$/, '$1') || '/';
    return p;
  }
  return `${u.origin}${u.pathname}`;
}

/** Blocks (first class of each classed div), their links and images, from a page's .plain.html. */
export function parsePlainHtml(html, origin) {
  const blocks = [];
  const loose = { name: 'default-content-wrapper', links: [], media: 0 };
  let cur = loose;
  const re = /<div class="([^"]+)"|<a\s[^>]*href="([^"]+)"|<img\s/g;
  let m;
  // eslint-disable-next-line no-cond-assign
  while ((m = re.exec(html))) {
    if (m[1]) {
      const name = m[1].split(/\s+/)[0];
      if (!NOT_BLOCKS.has(name)) {
        cur = { name, links: [], media: 0 };
        blocks.push(cur);
      }
    } else if (m[2]) {
      const link = toLink(m[2], origin);
      if (link && !cur.links.includes(link) && cur.links.length < 15) cur.links.push(link);
    } else cur.media = Math.min(5, cur.media + 1);
  }
  if (loose.links.length) blocks.push(loose);
  return blocks.map((b) => ({ ...b, form: /form/i.test(b.name) }));
}

/* <loc> URLs of a sitemap. Their origin may be the production host while `site` is .aem.live: only paths are kept. */
const locsOf = (xml) => [...xml.matchAll(/<loc>\s*([^<\s]+)\s*<\/loc>/g)].map((x) => decodeHtml(x[1]));

async function pool(items, n, fn) {
  const out = new Array(items.length);
  let i = 0;
  await Promise.all(Array.from({ length: Math.min(n, items.length) }, async () => {
    while (i < items.length) {
      const k = i;
      i += 1;
      // eslint-disable-next-line no-await-in-loop
      out[k] = await fn(items[k], k);
    }
  }));
  return out;
}

/**
 * Read a site's pages and their blocks into a profile.
 * Pages: /query-index.json (EDS), else /sitemap.xml (and the sitemaps it lists).
 * Blocks and links: each page's .plain.html (the first `maxPages` in rank order);
 * pages not crawled reuse the blocks of a crawled page in the same section.
 * Header and footer links: /nav.plain.html and /footer.plain.html.
 *
 * Rank (and so traffic share) is a guess: the homepage first, then shallow paths
 * before deep ones. Edit `share` in the profile when you know better.
 *
 * @param {object} o
 * @param {string} o.site          'https://main--site--org.aem.live' or the production origin
 * @param {number} [o.maxPages=40] pages to crawl for blocks
 * @param {number} [o.limit=300]   pages to keep
 * @param {RegExp} [o.exclude]     paths to skip (default: library, drafts, fragments, tools, nav, footer)
 * @param {typeof fetch} [o.fetch]
 * @param {object} [o.overrides]   profile fields to set (viewsPerDay, scenarios, ...)
 */
export async function buildProfile({
  site, maxPages = 40, limit = 300, exclude = SKIP_PATHS, fetch: fetchImpl = globalThis.fetch, overrides = {}, onProgress,
} = {}) {
  if (!site) throw new Error('buildProfile needs `site` (e.g. https://main--site--org.aem.live)');
  const origin = new URL(site).origin;
  const get = async (p, type = 'text') => {
    try {
      const res = await fetchImpl(new URL(p, `${origin}/`).toString());
      if (!res.ok) return null;
      return type === 'json' ? await res.json() : await res.text();
    } catch { return null; }
  };
  let source = 'query-index.json';
  let raw = [];
  const qi = await get('/query-index.json', 'json');
  if (qi && Array.isArray(qi.data)) raw = qi.data.map((row) => row.path).filter(Boolean);
  if (!raw.length) {
    source = 'sitemap.xml';
    const xml = await get('/sitemap.xml');
    if (xml) {
      const locs = locsOf(xml);
      if (/<sitemapindex/i.test(xml)) {
        // child sitemaps live on the production host too: fetch them from `site`
        const subs = await pool(locs.slice(0, 10), 4, (u) => get(new URL(u).pathname));
        raw = subs.filter(Boolean).flatMap(locsOf);
      } else raw = locs;
    }
  }
  const asPath = (p) => {
    try { return toLink(/^https?:/i.test(p) ? new URL(p).pathname : p, origin); } catch { return null; }
  };
  const seen = new Set();
  let paths = raw.map(asPath).filter((p) => p && isInternal(p) && !exclude.test(p) && !seen.has(p) && seen.add(p));
  if (!paths.length) throw new Error(`No pages found at ${origin} (tried /query-index.json and /sitemap.xml). Write profile.pages by hand.`);
  const depth = (p) => (p === '/' ? 0 : p.split('/').filter(Boolean).length);
  paths = paths.map((p, i) => [p, i]).sort((a, b) => depth(a[0]) - depth(b[0]) || a[1] - b[1]).map(([p]) => p).slice(0, limit);

  const crawl = paths.slice(0, maxPages);
  let done = 0;
  const parsed = await pool(crawl, 6, async (p) => {
    const html = await get(`${p === '/' ? '/index' : p}.plain.html`);
    done += 1;
    onProgress?.(done, crawl.length);
    return html ? parsePlainHtml(html, origin) : null;
  });
  const blocksOf = new Map(crawl.map((p, i) => [p, parsed[i]]).filter(([, b]) => b && b.length));
  const section = (p) => p.split('/').filter(Boolean)[0] || '';
  const pages = paths.map((p) => {
    let blocks = blocksOf.get(p);
    if (!blocks) {
      const twin = [...blocksOf.keys()].find((q) => q !== '/' && section(q) === section(p) && depth(q) === depth(p))
        || [...blocksOf.keys()].find((q) => q !== '/' && section(q) === section(p));
      blocks = twin ? blocksOf.get(twin) : [{ name: 'hero', links: [], media: 1 }, { name: 'columns', links: [], media: 1 }, { name: 'cards', links: [], media: 2 }];
    }
    return { path: p, blocks };
  });
  const linksOf = async (p) => {
    const html = await get(p);
    return html ? [...new Set(parsePlainHtml(html, origin).flatMap((b) => b.links))] : null;
  };
  const header = await linksOf('/nav.plain.html');
  const footer = await linksOf('/footer.plain.html');
  const { pages: _p, header: _h, footer: _f, ...defaults } = DEFAULT_PROFILE;
  return {
    fake: true,
    about: `Fake-data profile for optel-fake.js, read from ${origin}/${source} on ${new Date().toISOString().slice(0, 10)}. Page shares are guesses (homepage first, shallow before deep): edit them.`,
    ...defaults,
    site: origin,
    header: header && header.length ? header.slice(0, 12) : null,
    footer: footer && footer.length ? footer.slice(0, 20) : null,
    ...overrides,
    pages,
  };
}

/**
 * Turn what a user typed into a profile object:
 *   true | '1' | 'true' → {} (generic site); 'https://…' → buildProfile; 'file.json' → read it (Node);
 *   an object → itself. `scenarios` ('ai-growth,cwv-regression' or an array) are added.
 */
export async function resolveProfile(input, { scenarios, fetch: fetchImpl, onProgress } = {}) {
  let profile;
  if (input == null || input === true || input === '1' || input === 'true' || input === '') profile = {};
  else if (typeof input === 'object') profile = { ...input };
  else if (/^https?:\/\//i.test(input)) profile = await buildProfile({ site: input, fetch: fetchImpl, onProgress });
  else {
    const { readFile } = await import('node:fs/promises');
    profile = JSON.parse(await readFile(input, 'utf8'));
  }
  const extra = typeof scenarios === 'string' ? scenarios.split(',').map((s) => s.trim()).filter(Boolean) : (scenarios || []);
  if (extra.length) profile.scenarios = [...(profile.scenarios || []), ...extra];
  compileProfile(profile); // fail early on a bad scenario or cwv value
  return profile;
}

